import type { Metadata } from "next";
import { routes } from "@/config/routes";
import { seoDefaults } from "@/config/seo";
import { isIndexable, siteConfig } from "@/config/site";
import type { StaticPage } from "@/content/pages";
import { getSector } from "@/content/sectors";
import { getService } from "@/content/services";
import type { SectorSlug, ServiceSlug } from "@/types/content";
import type { PageSeoInput } from "@/types/seo";
import { absoluteUrl } from "./canonical";

/**
 * Builds the complete metadata object for one page. Every indexable page uses
 * this helper so titles, canonical URLs, Open Graph and X fields stay
 * consistent. Child metadata replaces the parent's openGraph and twitter
 * objects (shallow merge), so the shared images generated by
 * src/app/opengraph-image.tsx and twitter-image.tsx are referenced explicitly.
 */
const socialImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: seoDefaults.socialImageAlt,
};
export function buildMetadata(input: PageSeoInput): Metadata {
  const canonical = absoluteUrl(input.path);
  const indexable = isIndexable() && !input.noindex;
  const socialTitle = input.absoluteTitle
    ? input.title
    : seoDefaults.titleTemplate.replace("%s", input.title);

  return {
    title: input.absoluteTitle ? { absolute: input.title } : input.title,
    description: input.description,
    alternates: { canonical },
    robots: indexable
      ? { index: true, follow: true }
      : { index: false, follow: false },
    openGraph: {
      type: input.type ?? "website",
      locale: siteConfig.locale,
      siteName: siteConfig.name,
      url: canonical,
      title: socialTitle,
      description: input.description,
      images: [socialImage],
      ...(input.type === "article"
        ? {
            publishedTime: input.publishedTime,
            modifiedTime: input.modifiedTime,
          }
        : {}),
    },
    twitter: {
      card: seoDefaults.twitterCard,
      title: socialTitle,
      description: input.description,
      images: [{ ...socialImage, url: "/twitter-image" }],
    },
  };
}

export function buildStaticPageMetadata(page: StaticPage): Metadata {
  return buildMetadata({
    title: page.title,
    description: page.description,
    path: page.path,
    absoluteTitle: page.absoluteTitle,
  });
}

export function buildServiceMetadata(slug: ServiceSlug): Metadata {
  const service = getService(slug);
  return buildMetadata({
    title: service.seo.title,
    description: service.seo.description,
    path: routes.service(service.slug),
  });
}

export function buildSectorMetadata(slug: SectorSlug): Metadata {
  const sector = getSector(slug);
  return buildMetadata({
    title: sector.seo.title,
    description: sector.seo.description,
    path: routes.sector(sector.slug),
  });
}
